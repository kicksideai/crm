local test = require("test")
local fixture = require("fixture")
local handler = require("handler")
local function define_tests()
    test.describe("CRM reference query HTTP contract", function()
        test.it("reads declared references and forwards include_inactive to the reader", function()
            for _, kind in ipairs({ "references", "inbound_references" }) do
                for _, include_inactive in ipairs({ false, true }) do
                    fixture.reset({ kind = kind, from_ref = "crm:person:northwind", to_ref = "crm:company:northwind", include_inactive = include_inactive })
                    handler.query()
                    local response, called = fixture.result()
                    test.eq(response.status, 200)
                    test.eq(response.body.success, true)
                    test.eq(response.body.kind, kind)
                    test.eq(response.body.data[1].to_ref, "crm:company:northwind")
                    test.eq(called.crm_id, "northwind-crm")
                    test.eq(called.input.include_inactive, include_inactive)
                end
            end
        end)
        test.it("returns the timeline page with its next_cursor and forwards the cursor", function()
            fixture.reset({ kind = "timeline", record_id = "deal:1", limit = 1, cursor = "previous-page" })
            handler.query()
            local response, called = fixture.result()
            test.eq(response.status, 200)
            test.eq(response.body.success, true)
            test.eq(response.body.data[1].activity_id, "activity:2")
            test.eq(response.body.next_cursor, "next-timeline-page")
            test.eq(called.input.cursor, "previous-page")
        end)
        test.it("rejects an undeclared kind without calling the reader", function()
            fixture.reset({ kind = "undeclared" })
            handler.query()
            local response, called = fixture.result()
            test.eq(response.status, 400)
            test.eq(response.body.success, false)
            test.contains(response.body.error, "unknown CRM query kind")
            test.is_nil(called)
        end)
        test.it("classifies typed reference reader failures", function()
            fixture.reset({ kind = "references", from_ref = "crm:person:northwind" },
                errors.new({ kind = errors.INVALID, message = "cursor must be a next_cursor value" }))
            handler.query()
            local response = fixture.result()
            test.eq(response.status, 400)
            test.eq(response.body.success, false)
            test.eq(response.body.error, "cursor must be a next_cursor value")
        end)
    end)
end
return { run = test.run_cases(define_tests) }
